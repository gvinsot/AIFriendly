/**
 * Détection des panneaux d'administration exposés (/wp-admin, /phpmyadmin…).
 *
 * Une simple vérification du code HTTP (200/401/403) produit beaucoup de faux
 * positifs :
 *  - les SPA (Lovable, Vercel, Netlify…) renvoient index.html en HTTP 200 pour
 *    n'importe quel chemin ;
 *  - les WAF/CDN (Cloudflare, Akamai, Sucuri…) renvoient une page de blocage
 *    en 403 pour les chemins « suspects » comme /wp-admin — c'est justement la
 *    protection recommandée, pas une exposition ;
 *  - un 403 de l'origine signifie que l'accès est déjà refusé.
 *
 * Ce module ne dépend de rien (le fetch est injecté) afin d'être partagé entre
 * la webapp et le worker (copié dans worker/lib par le Dockerfile).
 */

export type AdminProbeFetcher = (
  url: string,
  init: RequestInit,
  timeoutMs: number
) => Promise<Response | null>;

export interface AdminPanelFinding {
  path: string;
  status: number;
  /** Produit identifié (WordPress, phpMyAdmin…) ou description générique. */
  product: string;
}

export interface AdminPanelDetectionResult {
  findings: AdminPanelFinding[];
  /** Chemins bloqués par un WAF/CDN, avec le fournisseur détecté. */
  wafBlocked: { path: string; provider: string }[];
}

interface ProbeResponse {
  status: number;
  headers: Headers;
  body: string;
}

interface AdminPathSpec {
  path: string;
  product: string;
  /** Empreinte attendue dans le corps d'une réponse 200. */
  fingerprint?: RegExp;
}

/** Chemins sondés. Sans empreinte → détection générique (formulaire de login). */
export const DEFAULT_ADMIN_PATHS: AdminPathSpec[] = [
  { path: "/admin", product: "Panneau d'administration" },
  { path: "/admin/", product: "Panneau d'administration" },
  { path: "/administrator", product: "Joomla", fingerprint: /joomla|com_login|mod-login/i },
  { path: "/wp-admin", product: "WordPress", fingerprint: /wp-login|wp-submit|wordpress|user_login/i },
  { path: "/wp-login.php", product: "WordPress", fingerprint: /wp-submit|user_login|wordpress|wp-login/i },
  { path: "/phpmyadmin", product: "phpMyAdmin", fingerprint: /phpmyadmin|pma_username|pma_password/i },
  { path: "/adminer.php", product: "Adminer", fingerprint: /adminer/i },
  { path: "/cpanel", product: "cPanel", fingerprint: /cpanel/i },
  { path: "/_admin", product: "Panneau d'administration" },
  { path: "/admin/login", product: "Panneau d'administration" },
  { path: "/manager/html", product: "Tomcat Manager", fingerprint: /tomcat/i },
  { path: "/solr/", product: "Apache Solr", fingerprint: /solr/i },
  { path: "/jenkins", product: "Jenkins", fingerprint: /jenkins/i },
];

const MAX_BODY_BYTES = 64 * 1024;
const PROBE_UA = "AIFriendly/1.0 (SecurityScan)";

/** Signatures des pages de blocage des principaux WAF/CDN. */
const WAF_SIGNATURES: { provider: string; test: (h: Headers, body: string) => boolean }[] = [
  {
    provider: "Cloudflare",
    test: (h, b) =>
      h.has("cf-mitigated") ||
      ((h.has("cf-ray") || /cloudflare/i.test(h.get("server") || "")) &&
        /sorry, you have been blocked|attention required!? \| cloudflare|cf-error-details|cloudflare ray id|cf-wrapper|challenge-platform/i.test(b)),
  },
  { provider: "Vercel", test: (h) => h.has("x-vercel-mitigated") },
  {
    provider: "Akamai",
    test: (h, b) =>
      (/akamai/i.test(h.get("server") || "") && /access denied/i.test(b)) ||
      /you don't have permission to access[\s\S]{0,300}reference\s*#[\d.a-f]+/i.test(b),
  },
  { provider: "AWS WAF / CloudFront", test: (_h, b) => /request blocked[\s\S]{0,400}cloudfront|generated by cloudfront[\s\S]{0,200}request blocked/i.test(b) },
  { provider: "Sucuri", test: (h, b) => h.has("x-sucuri-id") || h.has("x-sucuri-block") || /sucuri website firewall/i.test(b) },
  { provider: "Imperva / Incapsula", test: (h, b) => h.has("x-iinfo") || /incapsula incident id|_incapsula_resource/i.test(b) },
  { provider: "F5 BIG-IP ASM", test: (_h, b) => /the requested url was rejected\. please consult with your administrator/i.test(b) },
  { provider: "Wordfence", test: (_h, b) => /generated by wordfence|blocked by wordfence/i.test(b) },
  { provider: "ModSecurity", test: (_h, b) => /mod_?security|this error was generated by mod_security/i.test(b) },
  { provider: "WAF", test: (_h, b) => /sorry, you have been blocked|web application firewall|request (was )?blocked by (the )?(security|firewall)/i.test(b) },
];

/** Renvoie le fournisseur si la réponse est une page de blocage WAF/CDN. */
export function detectWafBlock(status: number, headers: Headers, body: string): string | null {
  // Les WAF bloquent en 403 le plus souvent, parfois 406/429/503 ou même 200.
  if (![200, 401, 403, 406, 429, 503].includes(status)) return null;
  for (const sig of WAF_SIGNATURES) {
    if (sig.test(headers, body)) return sig.provider;
  }
  return null;
}

function extractTitle(body: string): string {
  return (body.match(/<title[^>]*>([\s\S]*?)<\/title>/i)?.[1] || "").trim().toLowerCase();
}

/** Corps normalisé : retire les valeurs qui changent à chaque requête (nonces, tokens…). */
function normalizeBody(body: string): string {
  return body
    .replace(/\b(nonce|csrf[-_]?token|_token|request[-_]?id|ray[-_]?id)\s*[=:]\s*["']?[\w+/=-]+["']?/gi, "")
    .replace(/[0-9a-f]{16,}/gi, "")
    .replace(/\s+/g, " ")
    .trim();
}

/** Vrai si la réponse est identique (à peu près) à la page « catch-all » du site. */
function isSameAsBaseline(res: ProbeResponse, baseline: ProbeResponse | null): boolean {
  if (!baseline || res.status !== baseline.status) return false;
  const a = normalizeBody(res.body);
  const b = normalizeBody(baseline.body);
  if (a === b) return true;
  const maxLen = Math.max(a.length, b.length, 1);
  return extractTitle(res.body) === extractTitle(baseline.body) && Math.abs(a.length - b.length) / maxLen < 0.05;
}

/** Une page de login rendue côté serveur (les SPA n'ont pas ce champ dans le HTML initial). */
function looksLikeLoginPage(body: string): boolean {
  return /<input[^>]+type\s*=\s*["']?password/i.test(body) || /<title[^>]*>[^<]*(admin|login|log in|sign in|connexion)[^<]*<\/title>/i.test(body);
}

async function probe(fetcher: AdminProbeFetcher, url: string): Promise<ProbeResponse | null> {
  const res = await fetcher(url, { redirect: "manual", headers: { "User-Agent": PROBE_UA } }, 5000);
  if (!res) return null;
  return { status: res.status, headers: res.headers, body: await readHead(res, MAX_BODY_BYTES) };
}

/** Lit au plus `maxBytes` du corps (les signatures sont toujours en début de page). */
async function readHead(res: Response, maxBytes: number): Promise<string> {
  if (!res.body) return "";
  const reader = res.body.getReader();
  const decoder = new TextDecoder();
  let text = "";
  let bytes = 0;
  try {
    while (bytes < maxBytes) {
      const { done, value } = await reader.read();
      if (done) break;
      const chunk = value.subarray(0, maxBytes - bytes);
      bytes += chunk.byteLength;
      text += decoder.decode(chunk, { stream: true });
    }
    await reader.cancel().catch(() => {});
  } catch {
    // Corps illisible : on garde ce qui a été lu.
  } finally {
    reader.releaseLock();
  }
  return text + decoder.decode();
}

/**
 * Sonde les chemins d'administration et ne signale que les panneaux réellement
 * joignables (pas les pages catch-all de SPA, ni les blocages WAF, ni les 403).
 */
export async function detectAdminPanels(
  baseUrl: string,
  fetcher: AdminProbeFetcher,
  paths: AdminPathSpec[] = DEFAULT_ADMIN_PATHS
): Promise<AdminPanelDetectionResult> {
  // Chemin aléatoire inexistant : révèle le comportement « catch-all » du site.
  const randomPath = `/aifriendly-probe-${Math.random().toString(36).slice(2, 12)}`;
  const baseline = await probe(fetcher, new URL(randomPath, baseUrl).href);

  const findings: AdminPanelFinding[] = [];
  const wafBlocked: { path: string; provider: string }[] = [];

  await Promise.allSettled(
    paths.map(async (spec) => {
      const res = await probe(fetcher, new URL(spec.path, baseUrl).href);
      if (!res) return;

      const waf = detectWafBlock(res.status, res.headers, res.body);
      if (waf) {
        wafBlocked.push({ path: spec.path, provider: waf });
        return;
      }

      // 403 : l'accès est déjà refusé — c'est l'état recommandé.
      if (res.status !== 200 && res.status !== 401) return;
      if (isSameAsBaseline(res, baseline)) return;

      if (res.status === 401) {
        // Authentification HTTP propre à ce chemin : le panneau existe et est exposé au brute force.
        findings.push({ path: spec.path, status: 401, product: spec.product });
        return;
      }

      const matches = spec.fingerprint ? spec.fingerprint.test(res.body) : looksLikeLoginPage(res.body);
      if (matches) findings.push({ path: spec.path, status: 200, product: spec.product });
    })
  );

  const order = (p: string) => paths.findIndex((s) => s.path === p);
  findings.sort((a, b) => order(a.path) - order(b.path));
  wafBlocked.sort((a, b) => order(a.path) - order(b.path));
  return { findings, wafBlocked };
}
